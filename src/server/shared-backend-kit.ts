/**
 * Shared-tier backend kit — files injected into a generated app whose Petal
 * project is on the free SHARED backend tier (no dedicated database project).
 *
 * It exposes the SAME import surface as `backend-kit.ts`
 * (`@/integrations/backend/client`, `/auth`, `/types`) so generated app code
 * is identical whether the project is on the shared or dedicated tier. Under
 * the hood it talks to Petal's public shared REST API instead of Supabase.
 *
 * The project id + public API key are safe to embed (all access is scoped
 * server-side to that project and guarded by RLS-equivalent checks).
 */
import type { ProjectFile } from "@/server/generate.server";

export type SharedBackendKitOpts = {
  projectId: string;
  apiKey: string;
  /** Absolute origin of the Petal API, e.g. https://buildwithpetal.com */
  baseUrl: string;
};

function clientTs(o: SharedBackendKitOpts): string {
  return `// Auto-generated by Petal. Do not edit.
// Pre-configured Petal Cloud client (shared tier). Import from this file only.

const BASE = ${JSON.stringify(`${o.baseUrl.replace(/\/$/, "")}/api/public/shared/${o.projectId}`)};
const API_KEY = ${JSON.stringify(o.apiKey)};
const TOKEN_KEY = "petal.session";

export type PetalUser = { id: string; email: string; name: string | null };
export type PetalRecord<T = Record<string, unknown>> = {
  id: string;
  collection: string;
  user_id: string | null;
  data: T;
  created_at: string;
  updated_at: string;
};

export function getToken(): string | null {
  if (typeof window === "undefined") return null;
  return window.localStorage.getItem(TOKEN_KEY);
}

export function setToken(token: string | null) {
  if (typeof window === "undefined") return;
  if (token) window.localStorage.setItem(TOKEN_KEY, token);
  else window.localStorage.removeItem(TOKEN_KEY);
}

async function request<T>(path: string, init: RequestInit = {}): Promise<T> {
  const token = getToken();
  const res = await fetch(BASE + path, {
    ...init,
    headers: {
      "Content-Type": "application/json",
      "x-petal-key": API_KEY,
      ...(token ? { Authorization: "Bearer " + token } : {}),
      ...(init.headers as Record<string, string> | undefined),
    },
  });
  const body = (await res.json().catch(() => ({}))) as any;
  if (!res.ok) throw new Error(body?.error || "Request failed (" + res.status + ")");
  return body as T;
}

/** Typed data access. Collections are created on first write — no migrations. */
export const db = {
  list<T = Record<string, unknown>>(
    collection: string,
    opts: { mine?: boolean; limit?: number; offset?: number } = {},
  ): Promise<{ records: PetalRecord<T>[] }> {
    const q = new URLSearchParams();
    if (opts.mine) q.set("mine", "1");
    if (opts.limit) q.set("limit", String(opts.limit));
    if (opts.offset) q.set("offset", String(opts.offset));
    const qs = q.toString();
    return request("/records/" + encodeURIComponent(collection) + (qs ? "?" + qs : ""));
  },
  create<T = Record<string, unknown>>(collection: string, data: T): Promise<{ record: PetalRecord<T> }> {
    return request("/records/" + encodeURIComponent(collection), {
      method: "POST",
      body: JSON.stringify(data),
    });
  },
  update<T = Record<string, unknown>>(
    collection: string,
    id: string,
    data: Partial<T>,
  ): Promise<{ record: PetalRecord<T> }> {
    return request("/records/" + encodeURIComponent(collection) + "/" + id, {
      method: "PATCH",
      body: JSON.stringify(data),
    });
  },
  remove(collection: string, id: string): Promise<{ ok: true }> {
    return request("/records/" + encodeURIComponent(collection) + "/" + id, { method: "DELETE" });
  },
};

export const auth = {
  async signUp(email: string, password: string, name?: string) {
    const r = await request<{ token: string; user: PetalUser }>("/auth/signup", {
      method: "POST",
      body: JSON.stringify({ email, password, name }),
    });
    setToken(r.token);
    return r.user;
  },
  async signIn(email: string, password: string) {
    const r = await request<{ token: string; user: PetalUser }>("/auth/signin", {
      method: "POST",
      body: JSON.stringify({ email, password }),
    });
    setToken(r.token);
    return r.user;
  },
  async me(): Promise<PetalUser | null> {
    if (!getToken()) return null;
    try {
      const r = await request<{ user: PetalUser }>("/auth/me");
      return r.user;
    } catch {
      setToken(null);
      return null;
    }
  },
  signOut() {
    setToken(null);
  },
};
`;
}

const AUTH_TSX = `// Auto-generated by Petal. Do not edit.
// Auth provider + useAuth hook (Petal Cloud shared tier).
import { createContext, useContext, useEffect, useState, type ReactNode } from "react";
import { auth, type PetalUser } from "./client";

type AuthCtx = {
  user: PetalUser | null;
  loading: boolean;
  signIn: (email: string, password: string) => Promise<void>;
  signUp: (email: string, password: string, name?: string) => Promise<void>;
  signOut: () => void;
};

const Ctx = createContext<AuthCtx | null>(null);

export function AuthProvider({ children }: { children: ReactNode }) {
  const [user, setUser] = useState<PetalUser | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let alive = true;
    auth
      .me()
      .then((u) => alive && setUser(u))
      .finally(() => alive && setLoading(false));
    return () => {
      alive = false;
    };
  }, []);

  const value: AuthCtx = {
    user,
    loading,
    signIn: async (email, password) => setUser(await auth.signIn(email, password)),
    signUp: async (email, password, name) => setUser(await auth.signUp(email, password, name)),
    signOut: () => {
      auth.signOut();
      setUser(null);
    },
  };

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useAuth(): AuthCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useAuth must be used inside <AuthProvider>");
  return ctx;
}
`;

