export function getToken(): string | null {
  if (typeof window === "undefined") return null;
  return window.localStorage.getItem(TOKEN_KEY);
}

export function setToken(token: string | null) {
  if (typeof window === "undefined") return;
  if (token) window.localStorage.setItem(TOKEN_KEY, token);
  else window.localStorage.removeItem(TOKEN_KEY);
}

async function request<T>(path: string, init: RequestInit = {}): Promise<T> {
  const token = getToken();
  const headers = {
    "Content-Type": "application/json",
    "x-petal-key": API_KEY,
    ...(token ? { Authorization: "Bearer " + token } : {}),
    ...(init.headers as Record<string, string> | undefined),
  };
  // Try the remembered/primary address first, then the backups. We move on to
  // the next address when this one cannot answer for us: a transport failure,
  // an outage, or an address that does not recognise this app (401/404 —
  // the same key is valid everywhere, so that means we asked the wrong one).
  // Any genuine answer, including a rejected password, is returned as-is.
  const first = pickedBase();
  const order = [first, ...BASES.filter((b) => b !== first)];
  const RETRY_STATUS = [401, 404, 502, 503, 504];
  let lastError: Error | null = null;
  for (let i = 0; i < order.length; i++) {
    const base = order[i];
    const hasBackup = i < order.length - 1;
    let res: Response;
    try {
      res = await fetch(base + path, { ...init, headers });
    } catch (e) {
      lastError = e instanceof Error ? e : new Error("Network error");
      continue;
    }
    const body = (await res.json().catch(() => ({}))) as any;
    if (!res.ok) {
      const err = new Error(body?.error || "Request failed (" + res.status + ")");
      if (hasBackup && RETRY_STATUS.includes(res.status)) {
        lastError = err;
        continue;
      }
      throw err;
    }
    rememberBase(base);
    return body as T;
  }
  throw lastError || new Error("Request failed");
}

/** A list of records that can also be read as { records } — both styles work.
 *  \`total\` is set when the list was asked for with \`{ count: true }\`. */
export type RecordList<T> = PetalRecord<T>[] & { records: PetalRecord<T>[]; total?: number };

type FieldValue = string | number | boolean | null;
/** Server-side filter on a record's fields. A plain value means "equals". */
export type Where = Record<
  string,
  | FieldValue
  | { eq?: FieldValue; ne?: FieldValue; gt?: FieldValue; gte?: FieldValue; lt?: FieldValue; lte?: FieldValue; in?: FieldValue[]; contains?: string }
>;
export type ListOptions = {
  mine?: boolean;
  everyone?: boolean;
  /** e.g. { category: "dessert", price: { lte: 20 }, title: { contains: "cake" } } */
  where?: Where;
  /** Field name, "-" in front for descending: "price", "-createdAt". Default newest first. */
  sort?: string;
  limit?: number;
  offset?: number;
  /** Also return how many records match, as list.total. */
  count?: boolean;
};
/** One record that can also be read as { record } — both styles work. */
export type RecordResult<T> = PetalRecord<T> & { record: PetalRecord<T> };

function asList<T>(records: PetalRecord<T>[] | undefined, total?: number): RecordList<T> {
  const arr = (Array.isArray(records) ? records.slice() : []) as RecordList<T>;
  Object.defineProperty(arr, "records", { value: arr, enumerable: false });
  if (typeof total === "number") Object.defineProperty(arr, "total", { value: total, enumerable: false });
  return arr;
}

function asRecord<T>(record: PetalRecord<T>): RecordResult<T> {
  return Object.assign({}, record, { record }) as RecordResult<T>;
}

/** Typed data access. Collections are created on first write — no migrations. */
export const db = {
  async list<T = Record<string, unknown>>(
    collection: string,
    opts: ListOptions = {},
  ): Promise<RecordList<T>> {
    const q = new URLSearchParams();
    // Default: the signed-in user's rows + rows added by guests (starter rows).
    // everyone: every user's rows — for content meant to be public.
    if (opts.mine) q.set("mine", "1");
    else if (opts.everyone) q.set("scope", "all");
    // Filtering, sorting and paging run on the server — only matching rows travel.
    if (opts.where && Object.keys(opts.where).length) q.set("where", JSON.stringify(opts.where));
    if (opts.sort) q.set("sort", opts.sort);
    if (opts.limit) q.set("limit", String(opts.limit));
    if (opts.offset) q.set("offset", String(opts.offset));
    if (opts.count) q.set("count", "1");
    const qs = q.toString();
    const body = await request<{ records: PetalRecord<T>[]; total?: number }>(
      "/records/" + encodeURIComponent(collection) + (qs ? "?" + qs : ""),
    );
    return asList(body.records, body.total);
  },
  async create<T = Record<string, unknown>>(collection: string, data: T): Promise<RecordResult<T>> {
    const body = await request<{ record: PetalRecord<T> }>("/records/" + encodeURIComponent(collection), {
      method: "POST",
      body: JSON.stringify(data),
    });
    return asRecord(body.record);
  },
  async update<T = Record<string, unknown>>(
    collection: string,
    id: string,
    data: Partial<T>,
  ): Promise<RecordResult<T>> {
    const body = await request<{ record: PetalRecord<T> }>(
      "/records/" + encodeURIComponent(collection) + "/" + id,
      { method: "PATCH", body: JSON.stringify(data) },
    );
    return asRecord(body.record);
  },
  remove(collection: string, id: string): Promise<{ ok: true }> {
    return request("/records/" + encodeURIComponent(collection) + "/" + id, { method: "DELETE" });
  },
  /**
   * Starter records: writes the given rows into an EMPTY collection once, so a new
   * app opens with real, saved data instead of blank tables. Never touches a
   * collection that already holds records. Returns the current records (usable
   * as an array or as { records }).
   */
  async seedOnce<T = Record<string, unknown>>(collection: string, rows: T[]): Promise<RecordList<T>> {
    const current = await db.list<T>(collection, { limit: 1 });
    if (current.length > 0 || rows.length === 0) return db.list<T>(collection);
    const flag = "petal_seeded_" + API_KEY.slice(-8) + "_" + collection;
    if (typeof window !== "undefined" && window.localStorage.getItem(flag)) return current;
    // One all-or-nothing request: a half-written catalogue is impossible.
    await request("/records/" + encodeURIComponent(collection) + "/_seed", {
      method: "POST",
      body: JSON.stringify({ rows: rows.slice(0, 20) }),
    });
    if (typeof window !== "undefined") window.localStorage.setItem(flag, "1");
    return db.list<T>(collection);
  },
};

