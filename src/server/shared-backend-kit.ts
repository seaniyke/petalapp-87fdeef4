function siteUrl(to?: string): string {
  if (typeof window === "undefined") return to || "";
  return new URL(to || window.location.pathname + window.location.search, window.location.origin).toString();
}

function pickedBase(): string {
  if (typeof window === "undefined") return BASE;
  const saved = window.localStorage.getItem(BASE_KEY);
  return saved && BASES.includes(saved) ? saved : BASE;
}

function rememberBase(base: string) {
  if (typeof window !== "undefined") window.localStorage.setItem(BASE_KEY, base);
}

