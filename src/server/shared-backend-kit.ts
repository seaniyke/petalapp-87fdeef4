/**
 * Shared-tier backend kit — files injected into a generated app whose Kimble
 * project is on the free SHARED backend tier (no dedicated database project).
 *
 * It exposes the SAME import surface as `backend-kit.ts`
 * (`@/integrations/backend/client`, `/auth`, `/types`) so generated app code
 * is identical whether the project is on the shared or dedicated tier. Under
 * the hood it talks to Kimble's public shared REST API instead of Supabase.
 *
 * The project id + public API key are safe to embed (all access is scoped
 * server-side to that project and guarded by RLS-equivalent checks).
 */
import type { ProjectFile } from "@/server/generate.server";

export type SharedBackendKitOpts = {
  projectId: string;
  apiKey: string;
  /** Absolute origin of the Kimble API, e.g. https://buildwithpetal.com */
  baseUrl: string;
  /** Stable backup origins tried when the primary is unreachable or stale. */
  fallbackUrls?: string[];
};

function clientTs(o: SharedBackendKitOpts): string {
  return `// Auto-generated by Petal. Do not edit.
// Pre-configured Petal backend client (shared tier). Import from this file only.

const BASES = ${JSON.stringify(
    [o.baseUrl, ...(o.fallbackUrls ?? [])]
      .map((u) => `${u.replace(/\/$/, "")}/api/public/shared/${o.projectId}`)
      .filter((v, i, a) => a.indexOf(v) === i),
  )};
const BASE = BASES[0];
const API_KEY = ${JSON.stringify(o.apiKey)};
const TOKEN_KEY = "petal.session";
const BASE_KEY = "petal.api-base";

function pickedBase(): string {
  if (typeof window === "undefined") return BASE;
  const saved = window.localStorage.getItem(BASE_KEY);
  return saved && BASES.includes(saved) ? saved : BASE;
}

function rememberBase(base: string) {
  if (typeof window !== "undefined") window.localStorage.setItem(BASE_KEY, base);
}

export type PetalUser = { id: string; email: string; name: string | null };
export type PetalRecord<T = Record<string, unknown>> = {
  id: string;
  collection: string;
  user_id: string | null;
  data: T;
  created_at: string;
  updated_at: string;
};

export function getToken(): string | null {
  if (typeof window === "undefined") return null;
  return window.localStorage.getItem(TOKEN_KEY);
}

export function setToken(token: string | null) {
  if (typeof window === "undefined") return;
  if (token) window.localStorage.setItem(TOKEN_KEY, token);
  else window.localStorage.removeItem(TOKEN_KEY);
}

async function request<T>(path: string, init: RequestInit = {}): Promise<T> {
  const token = getToken();
  const headers = {
    "Content-Type": "application/json",
    "x-petal-key": API_KEY,
    ...(token ? { Authorization: "Bearer " + token } : {}),
    ...(init.headers as Record<string, string> | undefined),
  };
  // Try the remembered/primary address first, then the backups. We move on to
  // the next address when this one cannot answer for us: a transport failure,
  // an outage, or an address that does not recognise this app (401/404 —
  // the same key is valid everywhere, so that means we asked the wrong one).
  // Any genuine answer, including a rejected password, is returned as-is.
  const first = pickedBase();
  const order = [first, ...BASES.filter((b) => b !== first)];
  const RETRY_STATUS = [401, 404, 502, 503, 504];
  let lastError: Error | null = null;
  for (let i = 0; i < order.length; i++) {
    const base = order[i];
    const hasBackup = i < order.length - 1;
    let res: Response;
    try {
      res = await fetch(base + path, { ...init, headers });
    } catch (e) {
      lastError = e instanceof Error ? e : new Error("Network error");
      continue;
    }
    const body = (await res.json().catch(() => ({}))) as any;
    if (!res.ok) {
      const err = new Error(body?.error || "Request failed (" + res.status + ")");
      if (hasBackup && RETRY_STATUS.includes(res.status)) {
        lastError = err;
        continue;
      }
      throw err;
    }
    rememberBase(base);
    return body as T;
  }
  throw lastError || new Error("Request failed");
}

/** A list of records that can also be read as { records } — both styles work. */
export type RecordList<T> = PetalRecord<T>[] & { records: PetalRecord<T>[] };
/** One record that can also be read as { record } — both styles work. */
export type RecordResult<T> = PetalRecord<T> & { record: PetalRecord<T> };

function asList<T>(records: PetalRecord<T>[] | undefined): RecordList<T> {
  const arr = (Array.isArray(records) ? records.slice() : []) as RecordList<T>;
  Object.defineProperty(arr, "records", { value: arr, enumerable: false });
  return arr;
}

function asRecord<T>(record: PetalRecord<T>): RecordResult<T> {
  return Object.assign({}, record, { record }) as RecordResult<T>;
}

/** Typed data access. Collections are created on first write — no migrations. */
export const db = {
  async list<T = Record<string, unknown>>(
    collection: string,
    opts: { mine?: boolean; everyone?: boolean; limit?: number; offset?: number } = {},
  ): Promise<RecordList<T>> {
    const q = new URLSearchParams();
    // Default: the signed-in user's rows + rows added by guests (starter rows).
    // everyone: every user's rows — for content meant to be public.
    if (opts.mine) q.set("mine", "1");
    else if (opts.everyone) q.set("scope", "all");
    if (opts.limit) q.set("limit", String(opts.limit));
    if (opts.offset) q.set("offset", String(opts.offset));
    const qs = q.toString();
    const body = await request<{ records: PetalRecord<T>[] }>(
      "/records/" + encodeURIComponent(collection) + (qs ? "?" + qs : ""),
    );
    return asList(body.records);
  },
  async create<T = Record<string, unknown>>(collection: string, data: T): Promise<RecordResult<T>> {
    const body = await request<{ record: PetalRecord<T> }>("/records/" + encodeURIComponent(collection), {
      method: "POST",
      body: JSON.stringify(data),
    });
    return asRecord(body.record);
  },
  async update<T = Record<string, unknown>>(
    collection: string,
    id: string,
    data: Partial<T>,
  ): Promise<RecordResult<T>> {
    const body = await request<{ record: PetalRecord<T> }>(
      "/records/" + encodeURIComponent(collection) + "/" + id,
      { method: "PATCH", body: JSON.stringify(data) },
    );
    return asRecord(body.record);
  },
  remove(collection: string, id: string): Promise<{ ok: true }> {
    return request("/records/" + encodeURIComponent(collection) + "/" + id, { method: "DELETE" });
  },
  /**
   * Starter records: writes the given rows into an EMPTY collection once, so a new
   * app opens with real, saved data instead of blank tables. Never touches a
   * collection that already holds records. Returns the current records (usable
   * as an array or as { records }).
   */
  async seedOnce<T = Record<string, unknown>>(collection: string, rows: T[]): Promise<RecordList<T>> {
    const current = await db.list<T>(collection, { limit: 1 });
    if (current.length > 0 || rows.length === 0) return db.list<T>(collection);
    const flag = "petal_seeded_" + API_KEY.slice(-8) + "_" + collection;
    if (typeof window !== "undefined" && window.localStorage.getItem(flag)) return current;
    // One all-or-nothing request: a half-written catalogue is impossible.
    await request("/records/" + encodeURIComponent(collection) + "/_seed", {
      method: "POST",
      body: JSON.stringify({ rows: rows.slice(0, 20) }),
    });
    if (typeof window !== "undefined") window.localStorage.setItem(flag, "1");
    return db.list<T>(collection);
  },
};

export type PetalFile = { key: string; url: string; size: number; contentType: string };

/** File uploads (images up to 5 MB, PDFs). Returns a public URL to save on a record. */
export const storage = {
  async upload(file: File | Blob, name?: string): Promise<PetalFile> {
    const fileName = name || (file as File).name || "file";
    const token = getToken();
    const first = pickedBase();
    const order = [first, ...BASES.filter((b) => b !== first)];
    let lastError: Error | null = null;
    for (const base of order) {
      let res: Response;
      try {
        res = await fetch(base + "/uploads?name=" + encodeURIComponent(fileName), {
          method: "POST",
          headers: {
            "Content-Type": file.type || "application/octet-stream",
            "x-petal-key": API_KEY,
            ...(token ? { Authorization: "Bearer " + token } : {}),
          },
          body: file,
        });
      } catch (e) {
        lastError = e instanceof Error ? e : new Error("Network error");
        continue;
      }
      const body = (await res.json().catch(() => ({}))) as any;
      if (!res.ok) {
        lastError = new Error(body?.error || "Upload failed (" + res.status + ")");
        if ([401, 404, 502, 503, 504].includes(res.status)) continue;
        throw lastError;
      }
      rememberBase(base);
      return body.file as PetalFile;
    }
    throw lastError || new Error("Upload failed");
  },
  remove(key: string): Promise<{ ok: true }> {
    return request("/uploads/" + key.split("/").map(encodeURIComponent).join("/"), {
      method: "DELETE",
    });
  },
};

export const auth = {
  async signUp(email: string, password: string, name?: string) {
    const r = await request<{ token: string; user: PetalUser }>("/auth/signup", {
      method: "POST",
      body: JSON.stringify({ email, password, name }),
    });
    setToken(r.token);
    return r.user;
  },
  async signIn(email: string, password: string) {
    const r = await request<{ token: string; user: PetalUser }>("/auth/signin", {
      method: "POST",
      body: JSON.stringify({ email, password }),
    });
    setToken(r.token);
    return r.user;
  },
  async me(): Promise<PetalUser | null> {
    if (!getToken()) return null;
    try {
      const r = await request<{ user: PetalUser }>("/auth/me");
      return r.user;
    } catch {
      setToken(null);
      return null;
    }
  },
  signOut() {
    setToken(null);
  },

  // --- Parity aliases: same names + \`{ error }\` shape as the dedicated tier,
  // so page code written against either backend works unchanged.
  // Accepts (email, password) or the object form ({ email, password }) that
  // page code often writes — the object form used to send a 400.
  async signInWithPassword(emailOrCreds: string | Creds, password?: string): Promise<{ error: Error | null; user: PetalUser | null }> {
    try {
      const c = creds(emailOrCreds, password);
      const user = await auth.signIn(c.email, c.password);
      return { error: null, user };
    } catch (e) {
      return { error: e instanceof Error ? e : new Error("Sign in failed"), user: null };
    }
  },
  async signUpWithPassword(
    emailOrCreds: string | Creds,
    password?: string,
    name?: string,
  ): Promise<{ error: Error | null; user: PetalUser | null }> {
    try {
      const c = creds(emailOrCreds, password, name);
      const user = await auth.signUp(c.email, c.password, c.name);
      return { error: null, user };
    } catch (e) {
      return { error: e instanceof Error ? e : new Error("Sign up failed"), user: null };
    }
  },
};

export type Creds = { email: string; password: string; name?: string; options?: { data?: { name?: string; full_name?: string } } };
function creds(a: string | Creds, password?: string, name?: string): { email: string; password: string; name?: string } {
  if (typeof a === "object" && a) return { email: String(a.email ?? ""), password: String(a.password ?? ""), name: a.name ?? a.options?.data?.name ?? a.options?.data?.full_name };
  return { email: String(a ?? ""), password: String(password ?? ""), name };
}

`;
}

