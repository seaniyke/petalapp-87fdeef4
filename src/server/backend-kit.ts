export function backendKit(opts: BackendKitOpts): ProjectFile[] {
  return [
    { path: "src/integrations/backend/client.ts", content: clientTs(opts) },
    { path: "src/integrations/backend/auth.tsx", content: AUTH_TSX },
    { path: "src/integrations/backend/storage.ts", content: STORAGE_TS },
    { path: "src/integrations/backend/types.ts", content: TYPES_TS },
    { path: "src/components/examples/BACKEND.md", content: BACKEND_MD },
  ];
}

