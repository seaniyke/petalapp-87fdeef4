/**
 * Backend kit — files injected into a generated app when its Petal project
 * has an attached backend. Mirrors the style of `scaffold-kit.ts`: each
 * entry is overwrite-only and lives under `src/integrations/backend/` so the
 * AI cannot stomp on it.
 *
 * Credentials are baked in at injection time. URL + anon key are public
 * values (safe to embed). The service_role_key is never injected — it
 * stays server-side only, used by future managed features.
 */
import type { ProjectFile } from "@/server/generate.server";

export type BackendKitOpts = {
  url: string;
  anonKey: string;
};

function clientTs(opts: BackendKitOpts): string {
  return `// Auto-generated by Petal. Do not edit.
// Pre-configured backend client. Import from this file — never call createClient yourself.
import { createClient } from "@supabase/supabase-js";

const SUPABASE_URL = ${JSON.stringify(opts.url)};
const SUPABASE_ANON_KEY = ${JSON.stringify(opts.anonKey)};

export const supabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
  auth: {
    storage: typeof window !== "undefined" ? window.localStorage : undefined,
    persistSession: true,
    autoRefreshToken: true,
  },
});
`;
}

const AUTH_TSX = `// Auto-generated by Petal. Do not edit.
// Auth provider + useAuth hook. Wrap your app with <AuthProvider>.
import { createContext, useContext, useEffect, useState, type ReactNode } from "react";
import type { Session, User } from "@supabase/supabase-js";
import { supabase } from "./client";

type AuthCtx = {
  user: User | null;
  session: Session | null;
  loading: boolean;
  signInWithPassword: (email: string, password: string) => Promise<{ error: Error | null }>;
  signUpWithPassword: (email: string, password: string) => Promise<{ error: Error | null }>;
  signOut: () => Promise<void>;
  // Passwordless / OTP / recovery helpers (additive — existing apps unaffected).
  signInWithOtp: (email: string) => Promise<{ error: Error | null }>;
  verifyOtp: (email: string, token: string) => Promise<{ error: Error | null }>;
  resendSignupOtp: (email: string) => Promise<{ error: Error | null }>;
  resetPasswordForEmail: (email: string) => Promise<{ error: Error | null }>;
  updatePassword: (newPassword: string) => Promise<{ error: Error | null }>;
};

const Ctx = createContext<AuthCtx | null>(null);

export function AuthProvider({ children }: { children: ReactNode }) {
  const [session, setSession] = useState<Session | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    // IMPORTANT: subscribe BEFORE getSession to avoid missing the first event.
    const { data: sub } = supabase.auth.onAuthStateChange((_event, s) => {
      setSession(s);
      setLoading(false);
    });
    supabase.auth.getSession().then(({ data }) => {
      setSession(data.session);
      setLoading(false);
    });
    return () => sub.subscription.unsubscribe();
  }, []);

  const value: AuthCtx = {
    user: session?.user ?? null,
    session,
    loading,
    signInWithPassword: async (email, password) => {
      const { error } = await supabase.auth.signInWithPassword({ email, password });
      return { error: error ? new Error(error.message) : null };
    },
    signUpWithPassword: async (email, password) => {
      const { error } = await supabase.auth.signUp({
        email,
        password,
        options: { emailRedirectTo: typeof window !== "undefined" ? window.location.origin : undefined },
      });
      return { error: error ? new Error(error.message) : null };
    },
    signOut: async () => {
      await supabase.auth.signOut();
    },
    signInWithOtp: async (email) => {
      const { error } = await supabase.auth.signInWithOtp({
        email,
        options: { emailRedirectTo: typeof window !== "undefined" ? window.location.origin : undefined },
      });
      return { error: error ? new Error(error.message) : null };
    },
    verifyOtp: async (email, token) => {
      const { error } = await supabase.auth.verifyOtp({ email, token, type: "email" });
      return { error: error ? new Error(error.message) : null };
    },
    resendSignupOtp: async (email) => {
      const { error } = await supabase.auth.resend({ type: "signup", email });
      return { error: error ? new Error(error.message) : null };
    },
    resetPasswordForEmail: async (email) => {
      const { error } = await supabase.auth.resetPasswordForEmail(email, {
        redirectTo: typeof window !== "undefined" ? \`\${window.location.origin}/reset-password\` : undefined,
      });
      return { error: error ? new Error(error.message) : null };
    },
    updatePassword: async (newPassword) => {
      const { error } = await supabase.auth.updateUser({ password: newPassword });
      return { error: error ? new Error(error.message) : null };
    },
  };

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useAuth(): AuthCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useAuth must be used inside <AuthProvider>");
  return ctx;
}
`;

const STORAGE_TS = `// Auto-generated by Petal. Do not edit.
// Thin wrapper around Supabase Storage. Default bucket is "uploads".
import { supabase } from "./client";

export async function uploadFile(bucket: string, path: string, file: File | Blob) {
  const { data, error } = await supabase.storage.from(bucket).upload(path, file, {
    upsert: true,
  });
  if (error) throw error;
  return data;
}

export function getPublicUrl(bucket: string, path: string): string {
  const { data } = supabase.storage.from(bucket).getPublicUrl(path);
  return data.publicUrl;
}

export async function listFiles(bucket: string, prefix = "") {
  const { data, error } = await supabase.storage.from(bucket).list(prefix);
  if (error) throw error;
  return data ?? [];
}

export async function removeFile(bucket: string, path: string) {
  const { error } = await supabase.storage.from(bucket).remove([path]);
  if (error) throw error;
}
`;

