// Paystack signs the RAW request body with HMAC-SHA512 using your secret key
// and sends the hex digest in the \`x-paystack-signature\` header.

import { createHmac, timingSafeEqual } from "node:crypto";

const PAYSTACK_SECRET_KEY =
  (typeof process !== "undefined" ? process.env.PAYSTACK_SECRET_KEY : undefined) ?? "";

export type PaystackEvent = {
  event: string;
  data: Record<string, unknown> & { reference?: string; amount?: number; currency?: string };
};

export type WebhookResult =
  | { ok: true; event: PaystackEvent }
  | { ok: false; error: string; status: number };

export function verifyPaystackWebhook(
  rawBody: string,
  signatureHeader: string | null,
): WebhookResult {
  if (!PAYSTACK_SECRET_KEY)
    return { ok: false, error: "PAYSTACK_SECRET_KEY not configured", status: 500 };
  if (!signatureHeader)
    return { ok: false, error: "Missing x-paystack-signature header", status: 400 };

  const expected = createHmac("sha512", PAYSTACK_SECRET_KEY).update(rawBody).digest("hex");
  const a = Buffer.from(expected);
  const b = Buffer.from(signatureHeader);
  if (a.length !== b.length || !timingSafeEqual(a, b)) {
    return { ok: false, error: "Invalid signature", status: 401 };
  }

  try {
    const event = JSON.parse(rawBody) as PaystackEvent;
    return { ok: true, event };
  } catch {
    return { ok: false, error: "Invalid JSON body", status: 400 };
  }
}
